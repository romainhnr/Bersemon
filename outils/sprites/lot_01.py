@sprite("ouroboros", "Ouroboros")
def ouroboros(t):
    import math
    t.mat("g", "5c5560", "e0d4b0")
    t.mat("v", "c8782c", "5a9ad8")      # ventre
    t.mat("f", FEU, FEU_BLEU)
    t.mat("k", OS)
    cx, cy, r = 24, 25, 15
    pts, ventre = [], []
    for i in range(0, 31):
        a = math.radians(215 + i * 10.6)          # de la nuque a la pointe de la queue
        ep = 5.2 - 3.9 * (i / 30) ** 1.3
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a), ep))
        ventre.append((cx + (r - ep * 0.55) * math.cos(a), cy + (r - ep * 0.55) * math.sin(a), ep * 0.42))
    # cretes de feu le long du dos
    for i in range(1, 27, 2):
        a = math.radians(215 + i * 10.6)
        ep = pts[i][2]
        x, y = cx + (r + ep + 1.5) * math.cos(a), cy + (r + ep + 1.5) * math.sin(a)
        t.p(C(pts[i][0], pts[i][1], x, y, 1.4, 0.4), "f", trait=0, ton=2 if i % 4 == 1 else 3)
    t.p(S(pts[::3]), "g", trait=0)
    t.p(S(ventre[::3]), "v", trait=0, sur="g")
    # la tete mord la queue
    t.p(B([(5, 17), (9, 11), (15, 10), (18, 14), (16, 20), (10, 22), (6, 21)]), "g", trait=2)
    t.p(P([(14, 11), (20, 6), (17, 13)]) | P([(11, 10), (14, 3), (14, 10)]), "k", trait=0)
    t.p(B([(5, 21), (9, 20), (14, 21), (12, 25), (7, 25)]), "g", trait=1, dl=-1)
    t.px([(7, 21), (9, 21), (11, 21), (8, 24), (10, 24)], "k", 4)
    t.oeil(10, 14, "f", 2, reflet=True)
    t.px([(6, 18), (7, 17)], "g", 0)
    t.px([(26, 11), (33, 14), (38, 22), (37, 31), (31, 38), (22, 39), (14, 35)], "f", 3)
